import { lazy } from 'react'
import { hardReload, recentlyReloaded } from './version-check'
import { reportError } from './report-error'

/**
 * Экран, который грузится по требованию, — с переживанием деплоя.
 *
 * Зачем нужна обёртка над `lazy`. Каждая сборка даёт файлам новые имена
 * (`History-DwjbELtw.js`). Человек, у которого приложение открыто со СТАРОЙ
 * сборки, тапает «Статистика» — браузер идёт за старым именем чанка, а на
 * сервере его уже нет. Хостинг у нас настроен как одностраничное приложение:
 * на неизвестный путь он отдаёт `index.html`. Браузер получает HTML вместо
 * скрипта и падает с «'text/html' is not a valid JavaScript MIME type»,
 * а человек видит «Что-то пошло не так».
 *
 * Так и случилось 03.09.2026 на `/history` сразу после выката: экран
 * открывался только после перезагрузки вручную.
 *
 * Ошибка эта — не поломка кода, а признак того, что вкладка отстала от
 * сервера. Правильная реакция ровно одна: перезагрузиться на свежую сборку.
 * Берём для этого ту же `hardReload`, что и вахтёр версии (`version-check`):
 * она сбрасывает кеши, сохраняет query и hash (в hash Telegram передаёт
 * initData — потерять его нельзя) и метит время перезагрузки.
 *
 * Защита от петли — `recentlyReloaded()`: если уже перезагружались меньше
 * двух минут назад, значит дело не в версии (чанк реально не отдаётся, сеть
 * лежит). Тогда пробрасываем ошибку дальше — пусть её покажет ErrorBoundary,
 * а не браузер крутит бесконечный цикл.
 *
 * const History = lazyRoute(() => import('../pages/History'))
 */
export function lazyRoute(importer) {
  return lazy(() =>
    importer().catch(error => {
      if (recentlyReloaded()) {
        // Уже пробовали — значит причина не в устаревшей вкладке.
        reportError(error, 'lazyRoute.failed-after-reload')
        throw error
      }
      reportError(error, 'lazyRoute.stale-chunk')
      hardReload()
      // Страница уже уходит на перезагрузку: возвращаем промис, который
      // никогда не разрешится, чтобы React не успел показать ошибку.
      return new Promise(() => {})
    })
  )
}
