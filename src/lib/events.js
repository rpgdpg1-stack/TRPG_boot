/**
 * Централизованные имена и хелперы для событий.
 */

export const EVENTS = {
  /**
   * Авторизация прошла успешно — currentUser теперь доступен.
   * Шлётся один раз за сессию, после ensureAuth().
   * Детали в evt.detail: объект пользователя.
   */
  USER_READY: 'user-ready',

  /**
   * Данные пользователя изменились: стрик, имя, настройки приватности и т.п.
   * Детали в evt.detail: новый объект пользователя.
   */
  USER_CHANGED: 'user-changed',

  /**
   * Личные данные изменились: пол, рост.
   * Пол влияет на то, чью гифку показывать, поэтому экраны с упражнениями
   * на это событие перечитывают каталог.
   * Детали в evt.detail: { sex, height_cm }.
   */
  PERSONAL_CHANGED: 'personal-changed',

  /**
   * Очередь оффлайн-операций изменилась (добавили/схлопнули/отправили).
   * Нужно бейджу статуса: без этого он показывал счётчик, снятый в момент
   * потери сети, и правки, сделанные оффлайн, в него не попадали.
   * Детали в evt.detail: { size }.
   */
  QUEUE_CHANGED: 'queue-changed',

  /**
   * Список любимых упражнений изменился (добавили/убрали).
   * Слушают: страница «Любимые упражнения» и сердечко в мини-модалке дня.
   */
  FAVORITES_CHANGED: 'favorites-changed',

  /**
   * Человек пришёл по ссылке-приглашению, и дружба обработана.
   * Детали: { name, already }. Слушает App — показывает сообщение.
   */
  FRIEND_INVITE: 'friend-invite',

  /**
   * Личные настройки аккаунта (закрепы и т.п.) прочитаны из базы или изменены.
   * Слушает карусель программ: закреп приезжает уже после первого кадра.
   */
  PREFS_CHANGED: 'prefs-changed',

  /**
   * Состав друзей изменился НЕ по действию на экране: человек пришёл по
   * реферальной ссылке, и дружба завелась в фоне уже после старта приложения.
   * Слушает страница «Друзья» — сбрасывает кеш и перечитывает список, иначе
   * новый друг виден только со следующего запуска.
   */
  FRIENDS_CHANGED: 'friends-changed',

  /**
   * Изменилось состояние сессии: появилась, пропала, вход сорвался.
   * Детали: { hasSession, broken }. Шлёт lib/session.js.
   * Слушают: плашка статуса (показать «Нет связи» вместо пустых данных) и
   * App (перечитать данные, когда сессия вернулась).
   */
  AUTH_STATE: 'auth-state'
}

/**
 * Отправить событие.
 */
export function emit(name, detail) {
  window.dispatchEvent(new CustomEvent(name, { detail }))
}

/**
 * Подписаться на событие. Возвращает функцию отписки.
 */
export function on(name, handler) {
  window.addEventListener(name, handler)
  return () => window.removeEventListener(name, handler)
}