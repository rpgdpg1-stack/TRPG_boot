import * as Sentry from '@sentry/react'
import { debug } from './debug'

/**
 * Отправить сбой в Sentry, не роняя приложение (FE-003 / FE-007).
 *
 * Зачем понадобилось. В коде было двадцать мест вида `.catch(() => {})` —
 * осознанное решение: старт приложения не должен падать из-за необязательного
 * шага. Логика верная, но следствие неприятное: в Sentry не попадало НИЧЕГО
 * из этих путей. Если у человека перестанут переезжать настройки из облака
 * или молча не сработает приглашение по ссылке — узнать об этом было неоткуда.
 *
 * Здесь тот же самый «не падать», но со следом: поведение не меняется,
 * а сбой становится видимым.
 *
 * Ставить НЕ везде, а там, где сбой означает потерю пользовательских данных
 * или молчаливую поломку сценария. Пустой `catch` остаётся законным для
 * заведомо необязательного (хаптика, предзагрузка соседнего дня, аналитика).
 *
 *   loadPrefs().catch(e => reportError(e, 'app.loadPrefs'))
 *
 * @param error — что поймали.
 * @param where — короткая метка места: «модуль.функция». Попадает в Sentry
 *                тегом `where`, по нему события группируются и фильтруются.
 * @param extra — необязательные детали (id, ключ, параметры вызова).
 */
export function reportError(error, where, extra) {
  // В разработке Sentry выключен (enabled: import.meta.env.PROD), поэтому
  // дублируем в консоль — иначе локально сбой останется незамеченным.
  debug('[error]', where, error)

  try {
    Sentry.captureException(error, {
      tags: { where },
      extra: extra || undefined
    })
  } catch {
    // Sentry не инициализирован (нет DSN) — это не повод падать здесь.
  }
}

/**
 * Готовый обработчик для промиса: `promise.catch(catchTo('app.loadPrefs'))`.
 * Короче, чем стрелка, и не даёт случайно проглотить ошибку молча.
 */
export function catchTo(where, extra) {
  return (error) => reportError(error, where, extra)
}
