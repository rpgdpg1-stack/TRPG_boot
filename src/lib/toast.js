/**
 * Короткое подтверждение внизу экрана.
 *
 * Зачем: кнопка с галочкой годится, пока она на экране. Но «Сохранить» в
 * конструкторе уводит назад, а «Создать упражнение» закрывает форму — человек
 * остаётся без ответа, получилось ли. Тост живёт в App и переживает переход,
 * поэтому подтверждение видно уже на новом экране.
 *
 * Не для ошибок действий, которые человек должен исправить: их показываем
 * рядом с самим действием (Toast tone="error" на месте), иначе он промотает
 * подтверждение и не поймёт, что чинить.
 */
import { EVENTS, emit } from './events'

export function showToast(text, tone = 'success') {
  if (!text) return
  emit(EVENTS.TOAST, { text, tone, nonce: Date.now() })
}
