/**
 * Ракета — знак режима «Быстрая тренировка». Силуэт по референсу Дмитрия:
 * корпус носом вверх-вправо, круглое окно, два крыла (левое и нижнее) и
 * ОТДЕЛЬНЫЙ хвост-пламя в нижнем левом углу.
 *
 * ТРИ СОСТОЯНИЯ:
 *   выключено          — серый корпус, хвоста нет;
 *   включено           — акцентный корпус, хвоста нет;
 *   включено + тренировка идёт (`flame`) — акцентный корпус + оранжевый хвост.
 * Хвост зажигается только когда тренировка реально запущена: «ракета летит»
 * должно значить движение, а не просто выбранный режим.
 *
 * `color` перебивает всё — им ракету красят под фон кнопки (на зелёной заливке
 * «Начать» она чёрная, как и текст кнопки).
 */
export default function RocketIcon({ size = 20, lit = false, flame = false, color }) {
  const tint = color || (lit ? 'var(--color-primary)' : 'var(--color-text-secondary)')

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      aria-hidden="true"
      style={{ display: 'block', flexShrink: 0 }}
    >
      {/* Корпус с крыльями — одна фигура, как в референсе. Окно вырезано
          правилом evenodd, поэтому сквозь него виден фон, а не заливка. */}
      <path
        fillRule="evenodd"
        clipRule="evenodd"
        d="M22.5 1.5h-1.9c-3.9 0-7.6 1.9-10.2 5.2l-.8 1H6.3c-1.6 0-3 .9-3.8 2.3L1 13.1h5.2l4.2 4.2v5.2l3.1-1.6c1.4-.8 2.3-2.2 2.3-3.8v-3.3l1-.8c3.3-2.6 5.2-6.3 5.2-10.2V1.5ZM16.2 9.2a1.8 1.8 0 1 1 0-3.6 1.8 1.8 0 0 1 0 3.6Z"
        fill={tint}
      />
      {/* Хвост — только пока тренировка идёт. */}
      {flame && (
        <path
          d="M5 16.6 7.4 19c-1 1-2.7 1.7-4.8 2 .3-2.1 1-3.8 2-4.8Z"
          fill="var(--color-streak)"
        />
      )}
    </svg>
  )
}
