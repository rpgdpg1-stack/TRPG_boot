/**
 * Иконка группы мышц — пиксель-арт фигурка с подсвеченной мышцей.
 *
 * Рисуется по мотивам эталонных PNG Дмитрия, но вектором и со скруглениями:
 * та же композиция (тело блоками + яркая заливка на нужной мышце), только
 * линии плавные, поэтому иконка не рассыпается на 16px и на ретине.
 *
 * ДВА ЦВЕТА:
 *  - тело — приглушённый белый, одинаковый у всех иконок (это «фон», подложка);
 *  - подсветка — `currentColor`, то есть ЦВЕТ ГРУППЫ от родителя. Так иконка
 *    и заголовок читаются одним объектом: «Грудь» и её силуэт в одном цвете.
 *    В эталонах подсветка была красной, но в приложении цвет группы уже работает
 *    как навигация (см. trpg-ui) — красный на всех группах эту навигацию бы сломал.
 *
 * Ноги/ягодицы рисуются от ДРУГОЙ базы (таз + две ноги), остальные — от торса.
 */

const BODY = 'rgba(255, 255, 255, 0.22)'

/** Торс: голова, шея, корпус, руки. Общая подложка для всех «верхних» групп. */
function TorsoBase() {
  return (
    <g fill={BODY}>
      <rect x="9.2" y="1.4" width="5.6" height="5.8" rx="1.9" />
      <rect x="10.7" y="6.9" width="2.6" height="2.2" />
      <rect x="6" y="9" width="12" height="12.6" rx="2.2" />
      <rect x="3.1" y="9.8" width="2.5" height="8.6" rx="1.25" />
      <rect x="18.4" y="9.8" width="2.5" height="8.6" rx="1.25" />
    </g>
  )
}

/** Ноги: таз и два бедра-голени. База для «Ноги» и «Ягодицы». */
function LegsBase() {
  return (
    <g fill={BODY}>
      <rect x="6.6" y="1.8" width="10.8" height="4.4" rx="1.7" />
      <rect x="7.2" y="6" width="4" height="15.8" rx="1.8" />
      <rect x="12.8" y="6" width="4" height="15.8" rx="1.8" />
    </g>
  )
}

/** Подсветка мышцы — всегда currentColor (цвет группы). */
const HL = { fill: 'currentColor' }

const SHAPES = {
  // Спина — широкая пластина через весь верх корпуса (широчайшие + трапеции).
  back: (
    <g {...HL}>
      <rect x="6.6" y="9.8" width="10.8" height="4.2" rx="1.1" />
    </g>
  ),

  // Грудь — две пластины на верхней части корпуса.
  chest: (
    <g {...HL}>
      <rect x="7.1" y="10" width="4.6" height="3.9" rx="1" />
      <rect x="12.3" y="10" width="4.6" height="3.9" rx="1" />
    </g>
  ),

  // Пресс — три ряда по два кубика.
  abs: (
    <g {...HL}>
      <rect x="9.1" y="13.1" width="2.7" height="2.1" rx="0.6" />
      <rect x="12.2" y="13.1" width="2.7" height="2.1" rx="0.6" />
      <rect x="9.1" y="15.6" width="2.7" height="2.1" rx="0.6" />
      <rect x="12.2" y="15.6" width="2.7" height="2.1" rx="0.6" />
      <rect x="9.1" y="18.1" width="2.7" height="2.1" rx="0.6" />
      <rect x="12.2" y="18.1" width="2.7" height="2.1" rx="0.6" />
    </g>
  ),

  // Плечи — шапки дельт: накрывают верх руки И верхний угол корпуса, поэтому
  // читаются как надетые на плечевой пояс, а не как отдельные пятна сбоку.
  shoulders: (
    <g {...HL}>
      <rect x="2.9" y="9.2" width="5.6" height="4.4" rx="2" />
      <rect x="15.5" y="9.2" width="5.6" height="4.4" rx="2" />
    </g>
  ),

  // Бицепс — бугор на ВНУТРЕННЕЙ стороне плеча, ближе к корпусу.
  biceps: (
    <g {...HL}>
      <rect x="4" y="10.4" width="2.4" height="4.4" rx="1.2" />
      <rect x="17.6" y="10.4" width="2.4" height="4.4" rx="1.2" />
    </g>
  ),

  // Трицепс — полоса по ВНЕШНЕЙ стороне плеча, уже бицепса.
  triceps: (
    <g {...HL}>
      <rect x="2.9" y="10.4" width="1.9" height="4.6" rx="0.95" />
      <rect x="19.2" y="10.4" width="1.9" height="4.6" rx="0.95" />
    </g>
  ),

  // Предплечья — нижняя половина рук.
  forearms: (
    <g {...HL}>
      <rect x="3.3" y="14.6" width="2.1" height="4" rx="1.05" />
      <rect x="18.6" y="14.6" width="2.1" height="4" rx="1.05" />
    </g>
  ),

  // Шея — воротник между головой и корпусом.
  neck: (
    <g {...HL}>
      <rect x="9.6" y="6.4" width="4.8" height="3.4" rx="1.1" />
    </g>
  ),

  // Руки (общая группа) — плечо целиком, обе стороны.
  arms: (
    <g {...HL}>
      <rect x="3.1" y="9.8" width="2.5" height="8.6" rx="1.25" />
      <rect x="18.4" y="9.8" width="2.5" height="8.6" rx="1.25" />
    </g>
  ),

  // Ноги — квадрицепсы, задняя поверхность и икры на обеих ногах.
  legs: (
    <g {...HL}>
      <rect x="7.6" y="6.6" width="3.2" height="5" rx="1.1" />
      <rect x="13.2" y="6.6" width="3.2" height="5" rx="1.1" />
      <rect x="7.9" y="12.3" width="2.6" height="4.4" rx="1" />
      <rect x="13.5" y="12.3" width="2.6" height="4.4" rx="1" />
      <rect x="8.2" y="17.4" width="2" height="3.6" rx="0.9" />
      <rect x="13.8" y="17.4" width="2" height="3.6" rx="0.9" />
    </g>
  ),

  // Ягодицы — таз.
  glutes: (
    <g {...HL}>
      <rect x="6.6" y="1.8" width="10.8" height="4.4" rx="1.7" />
    </g>
  )
}

/** Каким группам рисовать ноги вместо торса. */
const LEG_GROUPS = new Set(['legs', 'glutes'])

/**
 * @param group — ключ группы мышц (back/chest/legs/…), как в MUSCLE_GROUP_LABELS.
 * Незнакомая группа (например «разминка») → ничего не рисуем: пустая рамка
 * хуже, чем её отсутствие.
 */
export default function MuscleGroupIcon({ group, size = 16, style }) {
  const shape = SHAPES[group]
  if (!shape) return null

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      aria-hidden="true"
      style={{ display: 'block', flexShrink: 0, ...style }}
    >
      {LEG_GROUPS.has(group) ? <LegsBase /> : <TorsoBase />}
      {shape}
    </svg>
  )
}
