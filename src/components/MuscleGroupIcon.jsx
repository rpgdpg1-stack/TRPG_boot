/**
 * Иконка группы мышц — фигурка с подсвеченной мышцей.
 *
 * ГЕОМЕТРИЯ — от Дмитрия (нарисована в Figma), координаты один в один из его
 * SVG, поэтому viewBox нестандартный: у торса и ног он свой, зато цифры не
 * переписаны и правки из Figma переносятся копипастой.
 * Исходники: `design/muscle-icons/body-torso.svg` и `body-legs.svg`.
 *
 * ЗАЛИВКА — ГЛАВНОЕ ПРАВИЛО. Тело рисуется группой
 * `<g fill="#FFF" opacity="...">`, а НЕ отдельными полупрозрачными фигурами.
 * Разница принципиальная: прозрачность на каждой фигуре складывается в местах
 * перекрытия (плечевой пояс поверх рук и корпуса давал светлые пятна, силуэт
 * выглядел лоскутным). Прозрачность на ГРУППЕ применяется к уже собранной
 * картинке — силуэт получается ровно одного серого. Не менять на per-shape
 * fill с альфой, иначе пятна вернутся.
 *
 * Подсветка мышцы — отдельным слоем поверх, всегда `currentColor`, то есть
 * ЦВЕТ ГРУППЫ от родителя: иконка и заголовок читаются одним объектом.
 * В эталонах подсветка была красной, но цвет группы у нас работает как
 * навигация (см. trpg-ui) — единый красный её бы сломал.
 *
 * Ноги/ягодицы рисуются от ДРУГОЙ базы (таз + две ноги), остальные — от торса.
 */

const BODY_OPACITY = 0.24

// Квадратные окна одного размера (220) вокруг каждой фигуры — так торс и ноги
// в списке выглядят одним персонажем в одном масштабе.
const VIEWBOX = {
  torso: '290 0.5 220 220',
  legs: '10 7 220 220'
}

/** Торс: круглая голова, шея, руки, корпус, плечевой пояс (он и сшивает руки с телом). */
function TorsoBase() {
  return (
    <g fill="#FFFFFF" opacity={BODY_OPACITY}>
      <circle cx="400" cy="38" r="33" />
      <rect x="386" y="63.97" width="28" height="28" />
      <rect x="317" y="86" width="30" height="112" rx="15" />
      <rect x="453" y="86" width="30" height="112" rx="15" />
      <rect x="354" y="86" width="92" height="130" rx="21" />
      <rect x="317" y="82" width="166" height="35" rx="17.5" />
    </g>
  )
}

/** Ноги: таз и две ноги. */
function LegsBase() {
  return (
    <g fill="#FFFFFF" opacity={BODY_OPACITY}>
      <rect x="74" y="18" width="39" height="198" rx="19.5" />
      <rect x="127" y="18" width="39" height="198" rx="19.5" />
      <rect x="74" y="18" width="92" height="51.29" rx="16" />
    </g>
  )
}

/** Подсветка мышцы — всегда currentColor (цвет группы). */
