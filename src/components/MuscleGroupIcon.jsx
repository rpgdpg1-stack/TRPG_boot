/**
 * Иконка группы мышц — фигурка с подсвеченной мышцей.
 *
 * Рисуется по мотивам эталонных PNG Дмитрия, но вектором и со скруглениями:
 * та же композиция (тело + яркая заливка на нужной мышце), только линии плавные,
 * поэтому иконка не рассыпается на мелком размере и на ретине.
 *
 * ДВА ЦВЕТА:
 *  - тело — приглушённый белый, одинаковый у всех иконок (это «фон», подложка);
 *  - подсветка — `currentColor`, то есть ЦВЕТ ГРУППЫ от родителя. Так иконка
 *    и заголовок читаются одним объектом: «Грудь» и её силуэт в одном цвете.
 *    В эталонах подсветка была красной, но в приложении цвет группы уже работает
 *    как навигация (см. trpg-ui) — красный на всех группах эту навигацию бы сломал.
 *
 * СИЛУЭТ (правка по замечаниям Дмитрия): голова — ПОЛНЫЙ круг, а не скруглённый
 * квадрат; руки не висят отдельными брусками, а сшиты с корпусом плечевым поясом
 * (он перекрывает и руки, и верх корпуса — переход плавный); корпус сужен
 * с 12 до 9.6 единиц, иначе фигурка читалась пузатой.
 *
 * Исходники силуэта для Figma — `design/muscle-icons/`. Правишь форму там →
 * переносишь координаты сюда (viewBox один и тот же, 24×24).
 *
 * Ноги/ягодицы рисуются от ДРУГОЙ базы (таз + две ноги), остальные — от торса.
 */

const BODY = 'rgba(255, 255, 255, 0.22)'

/** Торс: круглая голова, шея, плечевой пояс, корпус, руки. */
function TorsoBase() {
  return (
    <g fill={BODY}>
      <circle cx="12" cy="4.2" r="2.9" />
      <rect x="10.8" y="6.4" width="2.4" height="2.6" />
      {/* Плечевой пояс идёт поверх рук и корпуса — он их и сшивает. */}
      <rect x="3.4" y="8.6" width="17.2" height="4.2" rx="2.1" />
      <rect x="7.2" y="8.6" width="9.6" height="13" rx="2.2" />
      <rect x="3.4" y="8.6" width="3" height="10.9" rx="1.5" />
      <rect x="17.6" y="8.6" width="3" height="10.9" rx="1.5" />
    </g>
  )
}

/** Ноги: таз и два бедра-голени. База для «Ноги» и «Ягодицы». */
function LegsBase() {
  return (
    <g fill={BODY}>
      <rect x="7" y="1.8" width="10" height="4.2" rx="1.8" />
      <rect x="7.4" y="5.6" width="3.7" height="16" rx="1.7" />
      <rect x="12.9" y="5.6" width="3.7" height="16" rx="1.7" />
    </g>
  )
}

/** Подсветка мышцы — всегда currentColor (цвет группы). */
