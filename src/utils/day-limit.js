/**
 * Правило «одна тренировка в сутки на раздел» — ОДНО описание на проект (ARCH-004).
 *
 * Само правило живёт на СЕРВЕРЕ: его применяет `api_finish_workout`, считая
 * сутки по Москве и сравнивая раздел программы. Клиент правило не дублирует и
 * не пытается предсказать — он отправляет завершение и показывает то, что
 * ответил сервер (`already_completed_today`). Так две вкладки и два устройства
 * не могут разойтись во мнении, засчитана тренировка или нет.
 *
 * Здесь — только ТЕКСТ для человека. Раньше он был записан дважды: дефолтом
 * внутри модалки завершения («1 силовая в день») и отдельной строкой в заплыве
 * («1 заплыв в день»). Формулировки жили порознь и разъезжались бы при первой
 * же правке; при изменении самого правила (скажем, два заплыва в день) пришлось
 * бы искать все места.
 *
 * Меняешь правило на сервере — меняешь подпись ЗДЕСЬ, и она обновится всюду.
 */

/** Как называется единица тренировки в каждом разделе — для фразы о лимите. */
const UNIT = {
  gym: 'силовая',
  pool: 'заплыв',
  cardio: 'кардио',
  stretch: 'растяжка'
}

/**
 * Подпись под результатом, когда сервер ответил «за сегодня уже засчитано».
 *
 * @param category — раздел программы ('gym' | 'pool' | 'cardio' | 'stretch').
 * @returns строка вида «Достигнут лимит — 1 заплыв в день.
 *          Этот заплыв в статистику не войдёт.»
 */
export function dayLimitNote(category = 'gym') {
  const unit = UNIT[category] || UNIT.gym
  // «Эта тренировка» звучит естественнее для силовой, «этот заплыв» — для плавания.
  const subject = category === 'pool' ? 'Этот заплыв' : 'Эта тренировка'
  return `Достигнут лимит — 1 ${unit} в день.\n${subject} в статистику не войдёт.`
}
