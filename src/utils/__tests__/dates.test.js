import { describe, it, expect } from 'vitest'
import { mskParts, mskDayKey, getTodayKey, getCurrentWeekKey, resolveWeeklyStreak } from '../dates'

/**
 * Даты по Москве (TEST-001).
 *
 * Почему именно эти функции. Приложение живёт по московским суткам: от них
 * зависит лимит «одна тренировка в день», недельная серия и границы периодов
 * статистики. Ошибка тут НЕ ПАДАЕТ — просто показывает не те цифры, а увидеть
 * её глазами почти нельзя: надо дождаться нужной даты. Тесты дают дождаться
 * её за секунду.
 *
 * Ключевые ловушки, ради которых всё написано:
 *  - вечер по UTC уже утро по МСК (+3), и тренировка попадает в другие сутки;
 *  - ISO-неделя считается от четверга и на переломе года ведёт себя неочевидно;
 *  - ключ недели обязан совпадать с тем, что считает Postgres ('IYYY-IW'),
 *    иначе серия на сервере и в интерфейсе разойдутся.
 */

describe('mskParts — раскладка по московскому времени', () => {
  it('прибавляет три часа к UTC', () => {
    expect(mskParts('2026-09-02T10:00:00Z')).toMatchObject({ y: 2026, m: 8, d: 2, hh: 13 })
  })

  it('вечер по UTC — это уже следующие сутки по Москве', () => {
    // 22:30 UTC = 01:30 МСК третьего числа. Классическая ловушка лимита суток.
    expect(mskParts('2026-09-02T22:30:00Z')).toMatchObject({ y: 2026, m: 8, d: 3, hh: 1 })
  })

  it('переход года по Москве наступает раньше, чем по UTC', () => {
    expect(mskParts('2025-12-31T21:00:00Z')).toMatchObject({ y: 2026, m: 0, d: 1 })
  })
})

describe('mskDayKey / getTodayKey — ключ суток', () => {
  it('формат YYYY-MM-DD с ведущими нулями', () => {
    expect(mskDayKey('2026-09-02T10:00:00Z')).toBe('2026-09-02')
    expect(mskDayKey('2026-01-05T10:00:00Z')).toBe('2026-01-05')
  })

  it('две тренировки в один московский день дают ОДИН ключ', () => {
    // Утро и поздний вечер по Москве — те же сутки, значит лимит сработает.
    expect(mskDayKey('2026-09-02T05:00:00Z')).toBe(mskDayKey('2026-09-02T20:00:00Z'))
  })

  it('23:00 и 22:00 по UTC — РАЗНЫЕ московские сутки', () => {
    // 22:00 UTC = 01:00 МСК следующего дня, 20:00 UTC = 23:00 МСК текущего.
    expect(mskDayKey('2026-09-02T20:00:00Z')).toBe('2026-09-02')
    expect(mskDayKey('2026-09-02T22:00:00Z')).toBe('2026-09-03')
  })

  it('getTodayKey совпадает с ключом текущего момента', () => {
    const now = new Date()
    expect(getTodayKey(now)).toBe(mskDayKey(now.toISOString()))
  })
})

describe('getCurrentWeekKey — ISO-ключ недели, как в Postgres', () => {
  const key = (iso) => getCurrentWeekKey(new Date(iso))

  it('понедельник и воскресенье одной недели дают один ключ', () => {
    expect(key('2026-08-31T09:00:00Z')).toBe(key('2026-09-06T09:00:00Z'))
  })

  it('воскресенье и следующий понедельник — РАЗНЫЕ недели', () => {
    expect(key('2026-09-06T09:00:00Z')).not.toBe(key('2026-09-07T09:00:00Z'))
  })

  it('формат — YYYY-WW с ведущим нулём', () => {
    expect(key('2026-01-08T12:00:00Z')).toMatch(/^\d{4}-\d{2}$/)
  })

  it('1 января 2026 относится к неделе 2026-01 (четверг внутри года)', () => {
    // 1 января 2026 — четверг, значит эта неделя уже первая неделя 2026-го.
    expect(key('2026-01-01T12:00:00Z')).toBe('2026-01')
  })

  it('конец декабря может относиться к первой неделе СЛЕДУЮЩЕГО года', () => {
    // 29-31 декабря 2025 (пн-ср) лежат в неделе, чей четверг — 1 января 2026.
    expect(key('2025-12-29T12:00:00Z')).toBe('2026-01')
  })

  it('начало января может относиться к последней неделе ПРЕДЫДУЩЕГО года', () => {
    // 1 января 2027 — пятница; четверг её недели (31.12.2026) лежит в 2026-м.
    expect(key('2027-01-01T12:00:00Z')).toBe('2026-53')
  })
})

describe('resolveWeeklyStreak — протухание серии', () => {
  it('серия за текущую неделю остаётся как есть', () => {
    expect(resolveWeeklyStreak(3, getCurrentWeekKey())).toBe(3)
  })

  it('серия с прошлой недели обнуляется', () => {
    expect(resolveWeeklyStreak(3, '2020-01')).toBe(0)
  })

  it('нулевая и отрицательная серия — всегда 0', () => {
    expect(resolveWeeklyStreak(0, getCurrentWeekKey())).toBe(0)
    expect(resolveWeeklyStreak(-1, getCurrentWeekKey())).toBe(0)
  })

  it('без ключа недели серию не трогаем', () => {
    // Старые записи без weekly_streak_week: обнулять их было бы враньём.
    expect(resolveWeeklyStreak(5, null)).toBe(5)
  })
})
