-- SEC-007 · SEC-008 — границы значений на уровне БАЗЫ.
--
-- Ограничение в таблице надёжнее проверки в функции: оно действует, кто бы
-- ни писал — приложение, миграция или запрос в обход интерфейса.
--
-- SEC-007. Вес и дистанция не имели границ: тип numeric(6,2) пропускал
--   9999.99 кг. Опасность не в «обмане» (соревноваться в продукте не с кем),
--   а в графике весов: одна точка в 9999 расплющит все настоящие 60–110 кг
--   в линию у нижнего края, и график станет нечитаемым — пока ту точку
--   не удалить руками.
--   Границы: 500 кг (мировой рекорд в приседе ~350) и 100 км (марафонский
--   заплыв ~50 км). Живой человек в них не упрётся.
--
-- SEC-008. Заметки не имели предела длины. Лимит 280 символов живёт
--   В БРАУЗЕРЕ (maxLength поля + обрезка при сохранении в lib/notes.js) и
--   никак не мешает отправить запрос напрямую с текстом на мегабайт: ключ
--   публичный, он лежит в бандле. Один человек мог залить сотни мегабайт,
--   а квота бесплатного тарифа общая для всех.
--   Ставим ровно те же 280: обычный человек границы не заметит никогда,
--   потому что поле и так не даст ввести больше, а запрос в обход упрётся
--   в базу. Запас не нужен — чем ближе к настоящему лимиту, тем лучше защита.
--
-- Данные на момент миграции: максимум веса 110 кг, дистанции 2250 м,
-- самая длинная заметка 61 символ. Ни одна существующая строка не нарушает.
-- ============================================================================

ALTER TABLE public.user_exercise_weights
  ADD CONSTRAINT user_exercise_weights_kg_range
  CHECK (weight_kg >= 0 AND weight_kg <= 500);

ALTER TABLE public.user_exercise_weight_history
  ADD CONSTRAINT user_exercise_weight_history_kg_range
  CHECK (weight_kg >= 0 AND weight_kg <= 500);

ALTER TABLE public.workouts
  ADD CONSTRAINT workouts_distance_range
  CHECK (distance_m IS NULL OR (distance_m >= 0 AND distance_m <= 100000));

ALTER TABLE public.user_exercise_notes
  ADD CONSTRAINT user_exercise_notes_length
  CHECK (char_length(note) <= 280);

COMMENT ON CONSTRAINT user_exercise_notes_length ON public.user_exercise_notes IS
  'Тот же предел, что maxLength поля заметки во фронте (NOTE_MAX_LENGTH). Меняешь там — меняй и здесь.';
