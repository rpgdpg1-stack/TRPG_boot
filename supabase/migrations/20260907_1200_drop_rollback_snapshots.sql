-- SEC: снимки откатов больше не лежат в базе открытыми
--
-- Что было. Перед миграциями SEC-001 (02.09.2026) и DB-integrity (03.09.2026)
-- прежние определения функций сохранялись «на всякий случай» в таблицы
-- public._rollback_sec001 (15 функций) и public._rollback_db_integrity (3).
-- RLS на них не включался — а значит полный исходный код серверных функций,
-- включая проверки доступа, читался по ПУБЛИЧНОМУ anon-ключу кем угодно.
-- Тем же ключом их можно было переписать или очистить.
--
-- Почему удаляем, а не закрываем политиками. Обе миграции давно применены и
-- отработали, а сами снимки дублируют то, что и так лежит в репозитории:
-- supabase/schema.sql версионируется в git, и версия ДО правки достаётся
-- обычным `git show <коммит>^:supabase/schema.sql`. Держать вторую копию в
-- боевой базе, да ещё и открытую, смысла нет.
--
-- Откат к до-SEC-001 состоянию:  git show 0996ff1^:supabase/schema.sql
-- Откат к до-DB-integrity:       git show 4b2bd90^:supabase/schema.sql

DROP TABLE IF EXISTS public._rollback_sec001;
DROP TABLE IF EXISTS public._rollback_db_integrity;
