-- SEC-002 (исправление): каталог упражнений снова читается

-- ЧТО СЛОМАЛОСЬ. Миграция 20260902_1200 (SEC-002) убрала политику
-- public_read_exercises с USING (true) — правильно, она открывала чужие ЛИЧНЫЕ
-- упражнения всем. Но расчёт был на то, что чтение каталожных разрешит
-- оставшаяся exercises_public_reads_system_only. А она объявлена
-- AS RESTRICTIVE — такая политика только ОГРАНИЧИВАЕТ: её условие
-- добавляется через AND к разрешающим и сама она не разрешает ничего.
-- Разрешающих не осталось ни одной, и прямой select из exercises стал
-- возвращать ПУСТОЙ список — без ошибки, с кодом 200.

-- ЧТО ЭТО ДАЛО В ПРИЛОЖЕНИИ. Экраны, где каталог идёт через RPC
-- api_get_all_exercises (SECURITY DEFINER, RLS её не касается), работали как
-- раньше, поэтому поломку не было видно. А два места ходят в таблицу напрямую:
--   - конструктор программ (loadExerciseCatalog): вместо названий рисовались
--     сырые id («ex_001») и заглушки вместо превью;
--   - карточка упражнения (getExerciseById) для каталожных.
-- Пока на устройстве лежал прежний кеш каталога, всё выглядело исправным —
-- ломалось только там, где кеша не было.

-- ПОЧЕМУ ИМЕННО ТАК. Возвращаем разрешающую политику, но не прежнюю
-- USING (true), а суженную до каталожных: owner_id IS NULL. Дыра из SEC-002
-- не открывается — чужие личные упражнения прямым select по-прежнему не
-- достать, они отдаются только через api_get_my_exercises и loadExercisesByIds.
-- RESTRICTIVE-политику оставляем: теперь она делает ровно то, для чего
-- задумана, — страхует от повторного появления разрешающей с USING (true).

CREATE POLICY exercises_read_catalog ON public.exercises
  FOR SELECT TO anon, authenticated
  USING (owner_id IS NULL);
